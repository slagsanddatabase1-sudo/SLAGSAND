-- 1. Tables (Create if not exists)
create table if not exists public.pincodes (
  id bigint generated by default as identity primary key,
  pincode text not null unique,
  city text,
  district text,
  division text,
  delivery_status text default 'Delivery',
  price_ton numeric default 0,
  price_brass numeric default 0,
  price_foot numeric default 0,
  slag_basicrate numeric default 0,
  transportation_rate numeric default 0,
  unloading_charges numeric default 0,
  final_price numeric default 0,
  is_active boolean default true,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

create table if not exists public.inquiries (
  id bigint generated by default as identity primary key,
  type text not null,
  name text not null,
  contact text not null,
  email text,
  details jsonb,
  status text default 'new',
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  user_details jsonb not null,
  order_details jsonb not null,
  amount numeric not null,
  payment_id text,
  payment_method text not null default 'online',
  status text default 'pending',
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

create table if not exists public.marketers (
  id bigint generated by default as identity primary key,
  name text not null,
  contact text not null,
  email text,
  location text,
  experience text,
  status text default 'pending',
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

create table if not exists public.faqs (
  id bigint generated by default as identity primary key,
  question text not null,
  answer text not null,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

create table if not exists public.testimonials (
  id bigint generated by default as identity primary key,
  client_name text not null,
  content text not null,
  rating integer default 5,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

create table if not exists public.counters (
  key text primary key,
  value integer default 0
);

create table if not exists public.user_roles (
  id bigint generated by default as identity primary key,
  email text not null unique,
  role text not null default 'editor', -- 'admin', 'manager', 'editor'
  status text default 'pending', -- 'pending', 'active'
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);


