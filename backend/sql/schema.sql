-- 4. Policies (Drop first to avoid duplication errors)

-- Pincodes
drop policy if exists "Public Read Pincodes" on public.pincodes;
create policy "Public Read Pincodes" on public.pincodes for select using (true);

drop policy if exists "Public Read All" on public.pincodes; -- cleanup old name if exists
create policy "Public Read All" on public.pincodes for select using (true);


-- FAQs
drop policy if exists "Public Read FAQs" on public.faqs;
create policy "Public Read FAQs" on public.faqs for select using (true);

-- Testimonials
drop policy if exists "Public Read Testimonials" on public.testimonials;
create policy "Public Read Testimonials" on public.testimonials for select using (true);

-- Counters
drop policy if exists "Public Read Counters" on public.counters;
create policy "Public Read Counters" on public.counters for select using (true);

-- Inquiries
drop policy if exists "Public Insert Inquiries" on public.inquiries;
create policy "Public Insert Inquiries" on public.inquiries for insert with check (true);

-- Orders
drop policy if exists "Public Insert Orders" on public.orders;
create policy "Public Insert Orders" on public.orders for insert with check (true);

-- Marketers
drop policy if exists "Public Insert Marketers" on public.marketers;
create policy "Public Insert Marketers" on public.marketers for insert with check (true);

-- User Roles
drop policy if exists "Public Read User Roles" on public.user_roles;
create policy "Public Read User Roles" on public.user_roles for select using (true);

drop policy if exists "Public Write User Roles" on public.user_roles;
create policy "Public Write User Roles" on public.user_roles for insert with check (true);

drop policy if exists "Public Delete User Roles" on public.user_roles;
create policy "Public Delete User Roles" on public.user_roles for delete using (true);
